import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createServer} from 'vite';
import react from '@vitejs/plugin-react';
import {fileURLToPath} from 'node:url';
import {mkdir,writeFile} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)('playwright'),root=fileURLToPath(new URL('..',import.meta.url));
const output=new URL('../../artifacts/page-navigation-20261115/',import.meta.url),checks=[];
const server=await createServer({root,configFile:false,plugins:[react(),{name:'deny-real-daemon',configureServer(s){s.middlewares.use('/_velella',(_req,res)=>{res.statusCode=403;res.end('Synthetic fixture only')})}}],server:{host:'127.0.0.1',port:0},logLevel:'error'});
let browser;
try{
  await mkdir(output,{recursive:true});await server.listen();
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],daemonRequests=[];
  page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(r.url().includes('/_velella'))daemonRequests.push(r.url())});
  const back=page.locator('.shell-history button[aria-label="返回"]'),forward=page.locator('.shell-history button[aria-label="前进"]');
  const shell=async name=>page.locator(`[data-shell-page="${name}"]`).waitFor();
  const selected=async id=>page.locator(`output[data-workspace="${id}"]`).waitFor();
  await page.goto(server.resolvedUrls.local[0]+'tests/page-navigation.html');
  await page.getByRole('button',{name:'打开项目 项目 A',exact:true}).click();await selected('A-0');
  await page.getByRole('button',{name:'项目 B',exact:true}).click();await selected('B-0');
  await page.getByRole('button',{name:'打开工作区 B 工作区 1',exact:true}).click();await selected('B-1');
  await back.click();await shell('home');assert.equal(await back.isDisabled(),true);
  await forward.click();await selected('B-1');checks.push('项目和工作区切换不进入方向历史，前进保留最新选择 B-1');
  await page.getByRole('button',{name:'设置',exact:true}).click();await shell('settings');
  await back.click();await selected('B-1');
  await page.getByRole('button',{name:'项目 C',exact:true}).click();await selected('C-0');
  assert.equal(await forward.isEnabled(),true);await forward.click();await shell('settings');
  await back.click();await selected('C-0');checks.push('返回后切换项目保留前进路径，设置返回保持最新项目 C');
  await forward.click();await shell('settings');
  await page.getByRole('button',{name:'取消',exact:true}).click();await selected('C-0');checks.push('设置自身返回入口同样保留最新项目');
  await back.click();await shell('home');
  await page.getByRole('button',{name:'打开项目 项目 A',exact:true}).click();await selected('A-0');
  assert.equal(await forward.isDisabled(),true);checks.push('返回后打开不同大页面会截断旧前进分支');
  await page.screenshot({path:fileURLToPath(new URL('project.png',output))});
  assert.deepEqual(await page.evaluate(()=>window.navigationQA.requests.filter(r=>/layout.save|terminal\.(open|input|control)|project.add|workbench.update/.test(r.cmd))),[]);
  checks.push('导航未提交终端、布局或项目变更请求');
  await page.evaluate(()=>window.navigationQA.selectTarget({kind:'ssh',host_id:'11111111-1111-4111-8111-111111111111',server_id:'22222222-2222-4222-8222-222222222222'}));
  await page.getByRole('button',{name:'打开项目 项目 A',exact:true}).waitFor();
  await page.waitForFunction(()=>[...document.querySelectorAll('.shell-history button')].every(b=>b.disabled));checks.push('切换主机重置页面历史');
  assert.deepEqual(errors,[]);assert.deepEqual(daemonRequests,[]);
  await writeFile(new URL('results.json',output),JSON.stringify({synthetic:true,checks,pageErrors:errors,daemonRequests},null,2));
  for(const check of checks)console.log('PASS '+check);
}finally{await browser?.close();await server.close()}
